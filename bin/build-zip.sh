#!/usr/bin/env bash
#
# Build the distributable plugin ZIP.
#
#   bash bin/build-zip.sh
#
# Produces dist/profitguard-for-woocommerce.zip containing ONLY what a merchant
# needs at runtime.
#
# WHAT IS DELIBERATELY LEFT OUT, and why:
#
#   vendor/          Composer installs PHPUnit and PHPCS here. The plugin has
#                    ZERO runtime dependencies - it uses a hand-written
#                    autoloader - so shipping a vendor tree would add megabytes
#                    and review surface for nothing.
#   tests/, bin/     Development tooling. Every extra PHP file in a .org plugin
#                    is a file a reviewer has to read and an attacker can probe.
#   samples/         Regenerated by the fixture script; not needed to use the
#                    plugin.
#   docker-compose.yml, .wp-env.json, phpcs.xml.dist, phpunit.xml.dist,
#   composer.json    Development configuration.
#
# The ZIP's single top-level directory must be the plugin slug, because that is
# what WordPress unpacks into wp-content/plugins/.

set -euo pipefail

SLUG="profitguard-for-woocommerce"
ROOT="$( cd "$( dirname "${BASH_SOURCE[0]}" )/.." && pwd )"
DIST="${ROOT}/dist"
STAGE="${DIST}/${SLUG}"

rm -rf "${DIST}"
mkdir -p "${STAGE}"

# An explicit allow-list, not an exclude-list. An exclude-list silently ships
# whatever gets added later; this cannot.
cp "${ROOT}/${SLUG}.php" "${STAGE}/"
cp "${ROOT}/uninstall.php" "${STAGE}/"
cp "${ROOT}/readme.txt"    "${STAGE}/"
cp "${ROOT}/LICENSE"       "${STAGE}/"

cp -r "${ROOT}/includes" "${STAGE}/includes"
cp -r "${ROOT}/assets"   "${STAGE}/assets"
cp -r "${ROOT}/languages" "${STAGE}/languages"

# Refuse to ship anything that should not be there, rather than trusting the
# copy list above to stay correct.
if find "${STAGE}" -name 'vendor' -o -name '*.dist' -o -name 'composer.json' | grep -q .; then
	echo "ERROR: development files reached the staging directory." >&2
	exit 1
fi

cd "${DIST}"

# `zip` is not installed everywhere - notably not in Git Bash on Windows - and
# requiring it would make the build fail on the machine this plugin is most
# likely to be built on. Python's zipfile module is equivalent and is present
# wherever Python is.
#
# Note the interpreter is TESTED, not just located: on Windows, `python3` is a
# Microsoft Store alias stub that satisfies `command -v` and then refuses to
# run, so a plain existence check picks an interpreter that does not work.
run_python() {
	for candidate in python3 python py; do
		if "${candidate}" -c 'import zipfile' >/dev/null 2>&1; then
			"${candidate}" -m zipfile -c "$1" "$2"
			return 0
		fi
	done
	return 1
}

if command -v zip >/dev/null 2>&1; then
	zip -r -q "${SLUG}.zip" "${SLUG}"
elif run_python "${SLUG}.zip" "${SLUG}"; then
	:
else
	echo "ERROR: need either 'zip' or a working Python to build the archive." >&2
	exit 1
fi

rm -rf "${STAGE}"

SIZE=$( du -h "${DIST}/${SLUG}.zip" | cut -f1 )
echo "Built ${DIST}/${SLUG}.zip  (${SIZE})"
